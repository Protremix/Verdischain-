  // ============================================================
  // BIP39 MNEMONIC GENERATION
  // ============================================================
  const ENTROPY_BITS = 128; // 16 bytes → 12 words
  const WORD_COUNT = 12;
  const wordIndex = {};
  BIP39_WORDLIST.forEach(function (w, i) { wordIndex[w] = i; });

  function generateMnemonic() {
    const entropy = new Uint8Array(16);
    crypto.getRandomValues(entropy);

    // Checksum: first 4 bits of SHA-256(entropy)
    const hash = sha256(entropy);
    const checksumBits = (hash[0] >> 4) & 0x0f;

    // Combine 128 bits entropy + 4 bits checksum = 132 bits = 12 × 11-bit words
    const words = [];
    for (let i = 0; i < WORD_COUNT; i++) {
      const bitStart = i * 11;
      let value = 0;
      for (let j = 0; j < 11; j++) {
        const bitIndex = bitStart + j;
        let bit;
        if (bitIndex < ENTROPY_BITS) {
          const byteIndex = bitIndex >> 3;
          const bitOffset = 7 - (bitIndex & 7);
          bit = (entropy[byteIndex] >> bitOffset) & 1;
        } else {
          const checkBitIndex = bitIndex - ENTROPY_BITS;
          bit = (checksumBits >> (3 - checkBitIndex)) & 1;
        }
        value = (value << 1) | bit;
      }
      words.push(BIP39_WORDLIST[value]);
    }
    return words.join(' ');
  }

  function validateMnemonic(mnemonic) {
    const words = mnemonic.trim().toLowerCase().split(/\s+/);
    if (words.length !== WORD_COUNT) return false;

    // Convert words to bits
    let bits = '';
    for (const w of words) {
      const idx = wordIndex[w];
      if (idx === undefined) return false;
      bits += idx.toString(2).padStart(11, '0');
    }

    // Extract entropy (128 bits) and checksum (4 bits)
    const entropyBits = bits.substring(0, ENTROPY_BITS);
    const checksumBits = bits.substring(ENTROPY_BITS, 132);

    // Reconstruct entropy bytes
    const entropy = new Uint8Array(16);
    for (let i = 0; i < 16; i++) {
      entropy[i] = parseInt(entropyBits.substring(i * 8, (i + 1) * 8), 2);
    }

    // Verify checksum
    const hash = sha256(entropy);
    const expected = ((hash[0] >> 4) & 0x0f).toString(2).padStart(4, '0');
    return checksumBits === expected;
  }

  function mnemonicToSeed(mnemonic) {
    const normalized = mnemonic.trim().toLowerCase();
    return sha256(new TextEncoder().encode(normalized));
  }

  // ============================================================
  // ED25519 KEY DERIVATION (via tweetnacl)
  // ============================================================
  function deriveKeypair(mnemonic) {
    if (typeof nacl === 'undefined') {
      throw new Error('tweetnacl library not loaded. Include nacl-fast.min.js before this script.');
    }
    const seed = mnemonicToSeed(mnemonic);
    const kp = nacl.sign.keyPair.fromSeed(seed);
    return { publicKey: kp.publicKey, secretKey: kp.secretKey };
  }

  // ============================================================
  // BASE58 (Bitcoin alphabet)
  // ============================================================
  const B58_ALPHABET = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
  const B58_INDEXES = {};
  for (let i = 0; i < B58_ALPHABET.length; i++) B58_INDEXES[B58_ALPHABET[i]] = i;

  function base58Encode(input) {
    // Count leading zeros
    let zeros = 0;
    while (zeros < input.length && input[zeros] === 0) zeros++;

    // Convert to base58
    const digits = [];
    for (let i = zeros; i < input.length; i++) {
      let carry = input[i];
      for (let j = 0; j < digits.length; j++) {
        carry += digits[j] << 8;
        digits[j] = carry % 58;
        carry = Math.floor(carry / 58);
      }
      while (carry > 0) {
        digits.push(carry % 58);
        carry = Math.floor(carry / 58);
      }
    }
    let result = '';
    for (let i = 0; i < zeros; i++) result += '1';
    for (let i = digits.length - 1; i >= 0; i--) result += B58_ALPHABET[digits[i]];
    return result;
  }

  function base58Decode(str) {
    const bytes = [];
    let zeros = 0;
    while (zeros < str.length && str[zeros] === '1') zeros++;

    let carry = 0;
    for (let i = zeros; i < str.length; i++) {
      const idx = B58_INDEXES[str[i]];
      if (idx === undefined) throw new Error('Invalid base58 character: ' + str[i]);
      carry = idx;
      for (let j = 0; j < bytes.length; j++) {
        carry += bytes[j] * 58;
        bytes[j] = carry & 0xff;
        carry >>= 8;
      }
      while (carry > 0) {
        bytes.push(carry & 0xff);
        carry >>= 8;
      }
    }
    // Add leading zeros
    for (let i = 0; i < zeros; i++) bytes.push(0);
    return new Uint8Array(bytes.reverse());
  }

  // ============================================================
  // SS58 ADDRESS ENCODING (Verdis network prefix 909)
  // ============================================================
  const SS58_PREFIX = 909;
  const SS58_PRE = new TextEncoder().encode('SS58PRE');

  function ss58Encode(publicKey) {
    if (publicKey.length !== 32) throw new Error('Public key must be 32 bytes');

    // Prefix 909 as 2 bytes LE: 0x8D, 0x03
    const prefixBytes = new Uint8Array([SS58_PREFIX & 0xff, (SS58_PREFIX >> 8) & 0xff]);

    // Checksum: Blake2b-512("SS58PRE" + prefix + pubkey), first 2 bytes
    const checksumInput = new Uint8Array(SS58_PRE.length + prefixBytes.length + publicKey.length);
    checksumInput.set(SS58_PRE, 0);
    checksumInput.set(prefixBytes, SS58_PRE.length);
    checksumInput.set(publicKey, SS58_PRE.length + prefixBytes.length);
    const fullHash = blake2b(checksumInput, 64);
    const checksum = fullHash.slice(0, 2);

    // Full payload: prefix + pubkey + checksum
    const payload = new Uint8Array(prefixBytes.length + publicKey.length + checksum.length);
    payload.set(prefixBytes, 0);
    payload.set(publicKey, prefixBytes.length);
    payload.set(checksum, prefixBytes.length + publicKey.length);

    return base58Encode(payload);
  }

  function ss58Decode(address) {
    const decoded = base58Decode(address);
    // prefix (2 bytes) + pubkey (32 bytes) + checksum (2 bytes) = 36
    if (decoded.length !== 36) throw new Error('Invalid SS58 address length: ' + decoded.length);

    const prefixBytes = decoded.slice(0, 2);
    const publicKey = decoded.slice(2, 34);
    const checksum = decoded.slice(34, 36);

    // Verify checksum
    const checksumInput = new Uint8Array(SS58_PRE.length + prefixBytes.length + publicKey.length);
    checksumInput.set(SS58_PRE, 0);
    checksumInput.set(prefixBytes, SS58_PRE.length);
    checksumInput.set(publicKey, SS58_PRE.length + prefixBytes.length);
    const expected = blake2b(checksumInput, 64).slice(0, 2);

    // Compare checksums
    for (let i = 0; i < 2; i++) {
      if (checksum[i] !== expected[i]) throw new Error('Invalid SS58 checksum');
    }
    return publicKey;
  }

  // ============================================================
  // WALLET STORAGE (async — uses crypto.subtle for AES-GCM)
  // ============================================================
  const STORAGE_KEY = 'verdis_wallet_account';

  async function derivePinKey(pin) {
    const enc = new TextEncoder();
    const keyMaterial = await crypto.subtle.importKey(
      'raw', enc.encode(pin), { name: 'PBKDF2' }, false, ['deriveKey']
    );
    return crypto.subtle.deriveKey(
      { name: 'PBKDF2', salt: enc.encode('verdis-wallet-salt'), iterations: 100000, hash: 'SHA-256' },
      keyMaterial,
      { name: 'AES-GCM', length: 256 },
      false,
      ['encrypt', 'decrypt']
    );
  }

  async function encryptData(data, pin) {
    const key = await derivePinKey(pin);
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const enc = new TextEncoder();
    const ciphertext = await crypto.subtle.encrypt(
      { name: 'AES-GCM', iv: iv },
      key,
      enc.encode(JSON.stringify(data))
    );
    // Combine iv + ciphertext as base64
    const combined = new Uint8Array(iv.length + ciphertext.byteLength);
    combined.set(iv, 0);
    combined.set(new Uint8Array(ciphertext), iv.length);
    return btoa(String.fromCharCode.apply(null, combined));
  }

  async function decryptData(b64, pin) {
    const key = await derivePinKey(pin);
    const combined = Uint8Array.from(atob(b64), c => c.charCodeAt(0));
    const iv = combined.slice(0, 12);
    const ciphertext = combined.slice(12);
    const decrypted = await crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: iv },
      key,
      ciphertext
    );
    return JSON.parse(new TextDecoder().decode(decrypted));
  }

  function uint8ToHex(arr) {
    return Array.from(arr).map(b => b.toString(16).padStart(2, '0')).join('');
  }

  function hexToUint8(hex) {
    return new Uint8Array(hex.match(/.{2}/g).map(b => parseInt(b, 16)));
  }

  async function createWallet(pin) {
    const mnemonic = generateMnemonic();
    const kp = deriveKeypair(mnemonic);
    const address = ss58Encode(kp.publicKey);
    const publicKeyHex = uint8ToHex(kp.publicKey);
    const secretKeyHex = uint8ToHex(kp.secretKey);

    const encryptedSecret = await encryptData({ secretKey: secretKeyHex, mnemonic: mnemonic }, pin);

    const account = { address: address, publicKey: publicKeyHex, enc: encryptedSecret };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(account));

    return { mnemonic: mnemonic, address: address, publicKey: publicKeyHex };
  }

  async function importWallet(mnemonic, pin) {
    const trimmed = mnemonic.trim().toLowerCase();
    if (!validateMnemonic(trimmed)) {
      throw new Error('Invalid BIP39 mnemonic phrase. Check your 12 words.');
    }
    const kp = deriveKeypair(trimmed);
    const address = ss58Encode(kp.publicKey);
    const publicKeyHex = uint8ToHex(kp.publicKey);
    const secretKeyHex = uint8ToHex(kp.secretKey);

    const encryptedSecret = await encryptData({ secretKey: secretKeyHex, mnemonic: trimmed }, pin);

    const account = { address: address, publicKey: publicKeyHex, enc: encryptedSecret };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(account));

    return { address: address, publicKey: publicKeyHex };
  }

  function loadWallet() {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    return JSON.parse(raw);
  }

  function hasWallet() {
    return localStorage.getItem(STORAGE_KEY) !== null;
  }

  function getAddress() {
    const w = loadWallet();
    return w ? w.address : null;
  }

  function clearWallet() {
    localStorage.removeItem(STORAGE_KEY);
  }

  async function exportMnemonic(pin) {
    const w = loadWallet();
    if (!w) throw new Error('No wallet found');
    const data = await decryptData(w.enc, pin);
    return data.mnemonic;
  }

  async function getSecretKey(pin) {
    const w = loadWallet();
    if (!w) throw new Error('No wallet found');
    const data = await decryptData(w.enc, pin);
    return hexToUint8(data.secretKey);
  }

